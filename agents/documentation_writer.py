"""Documentation writer: Markdown generated from extracted facts; every fact cites file:line."""
from __future__ import annotations

import re
from collections import defaultdict

from agents.common import AgentContext, AgentOutput, claims_from_llm
from verification.evidence_validator import Claim

KINDS = ["architecture", "modules", "api", "setup", "dependencies", "configuration", "developer_guide", "full"]


def _ref(path, a, b=None):
    return f"`{path}:{a}-{b or a}`"


class _Doc:
    def __init__(self, ctx: AgentContext, out: AgentOutput):
        self.ctx, self.out, self.md = ctx, out, []

    def fact(self, text: str, path: str, a: int, b: int | None = None, symbol: str = "") -> None:
        ev = self.ctx.span(path, a, b or a, symbol, ("graph", "doc-generator"))
        self.out.claims.append(Claim(text, "fact", [ev] if ev else []))
        self.md.append(f"- {text} ({_ref(path, a, b)})")

    def line(self, s: str = "") -> None:
        self.md.append(s)


def run(ctx: AgentContext, question: str, task: str = "documentation", options: dict | None = None) -> AgentOutput:
    options = options or {}
    kind = options.get("kind", "full")
    if kind not in KINDS:
        kind = "full"
    out = AgentOutput()
    g = ctx.graph()
    d = _Doc(ctx, out)
    repo = ctx.repo
    d.line(f"# {repo['name']} - generated documentation")
    d.line(f"_Revision `{repo['revision']}`. Generated by CodeMind OS from static analysis. Statements in "
           "**Verified repository facts** carry file:line references; **Suggested improvements** are recommendations, not facts._\n")
    want = lambda k: kind in {k, "full"}  # noqa: E731
    mods = [(n, x) for n, x in g.nodes(data=True) if x.get("type") == "Module" and not x.get("external")]
    mods.sort(key=lambda kv: kv[1]["path"])
    suggestions: list[tuple[str, str, str | None]] = []
    if want("architecture"):
        d.line("## Architecture overview\n### Verified repository facts")
        for n, m in mods:
            if m.get("attrs", {}).get("entry_point"):
                ml = m["attrs"].get("main_line", [1, 1])
                d.fact(f"`{m['path']}` is an executable entry point (`__main__` guard)", m["path"], ml[0], ml[1])
        dirs = defaultdict(int)
        for _, x in g.nodes(data=True):
            if x.get("type") == "File":
                dirs[x["path"].split("/")[0] if "/" in x["path"] else "(root)"] += 1
        d.line("- Files per top-level location: " + ", ".join(f"`{k}` ({v})" for k, v in sorted(dirs.items())) + " (from the file manifest)")
        d.line()
    if want("modules"):
        d.line("## Module reference\n### Verified repository facts")
        for n, m in mods:
            if m["language"] != "python" and not m.get("path"):
                continue
            doc = m.get("attrs", {}).get("docstring")
            ents = [(e, g.nodes[e]) for _, e, ed in g.out_edges(n, data=True) if ed["type"] == "CONTAINS"
                    and g.nodes[e].get("type") in {"Class", "Function", "DatabaseEntity"}]
            d.line(f"#### `{m['path']}`")
            if doc:
                d.fact(f"Module docstring: {doc}", m["path"], 1, min(m["end_line"], 30))
            else:
                suggestions.append((f"Add a module docstring to `{m['path']}`.", m["path"], None))
            for e, x in sorted(ents, key=lambda kv: kv[1]["start_line"]):
                sig = x.get("attrs", {}).get("signature") or f"{x['type'].lower()} {x['name']}"
                dd = x.get("attrs", {}).get("docstring")
                d.fact(f"{x['type']} `{x['name']}`: `{sig}`" + (f" - {dd}" if dd else ""), m["path"], x["start_line"], x["end_line"], x["qualified_name"])
                if not dd and x["type"] in {"Function", "Class"} and not x["name"].startswith("_"):
                    suggestions.append((f"Document public {x['type'].lower()} `{x['qualified_name']}` ({m['path']}:{x['start_line']}).", m["path"], None))
        d.line()
    if want("api"):
        d.line("## API summary\n### Verified repository facts")
        eps = sorted([x for _, x in g.nodes(data=True) if x.get("type") == "Endpoint"], key=lambda x: (x["path"], x["start_line"]))
        if not eps:
            d.line("- No HTTP endpoints were detected (decorator-pattern detection covers Python route decorators only).")
        for x in eps:
            doc = ""
            h = x.get("attrs", {}).get("handler", "")
            d.fact(f"`{x['name']}` handled by `{h}` (framework not verified)", x["path"], x["start_line"], x["end_line"], h)
        d.line()
    if want("configuration"):
        d.line("## Configuration reference\n### Verified repository facts")
        found = False
        for n, x in sorted(g.nodes(data=True), key=lambda kv: kv[1].get("name", "")):
            if x.get("type") == "ConfigKey":
                found = True
                for u, _, e in g.in_edges(n, data=True):
                    if e["type"] == "READS_CONFIG":
                        d.fact(f"Environment variable `{x['name']}` read in `{g.nodes[u].get('qualified_name')}`"
                               + (f"; declared in `{x['path']}`" if x.get("path") else "; no example declaration found"), e["path"], e["line"], e["line"])
                        if not x.get("path"):
                            suggestions.append((f"Declare `{x['name']}` in `.env.example`.", e["path"], None))
                        break
                else:
                    if x.get("path"):
                        d.fact(f"Config key `{x['name']}` is declared (never read by extracted code)", x["path"], x["start_line"], x["end_line"])
        if not found:
            d.line("- No environment-variable configuration detected.")
        d.line()
    if want("dependencies"):
        d.line("## Dependencies\n### Verified repository facts")
        ext = g.graph.get("external_imports", {})
        for name, cnt in sorted(ext.items(), key=lambda kv: -kv[1])[:20]:
            for u, v, e in g.in_edges(f"ext:{name}", data=True):
                d.fact(f"Imports external module `{name}` ({cnt} import statement(s))", e["path"], e["line"], e["line"])
                break
        for p in ("requirements.txt", "pyproject.toml", "package.json", "go.mod", "pom.xml"):
            if ctx.chunks.for_path(ctx.repo_id, p):
                n_lines = len(ctx.chunks.file_lines(ctx.repo_id, p))
                d.fact(f"Dependency manifest `{p}` is present", p, 1, min(n_lines, 40))
        d.line()
    if want("setup"):
        d.line("## Setup instructions\n### Verified repository facts")
        shown = False
        for p in ctx.chunks.paths(ctx.repo_id):
            if p.lower().startswith("readme"):
                for c in ctx.chunks.for_path(ctx.repo_id, p):
                    if re.search(r"(?i)install|setup|getting started|usage|run", c["symbol"]):
                        d.fact(f"README section '{c['symbol']}' describes setup/usage", p, c["start_line"], c["end_line"])
                        shown = True
        for p in ("Dockerfile", "docker-compose.yml", "Makefile"):
            if ctx.chunks.for_path(ctx.repo_id, p):
                d.fact(f"`{p}` is present and can be reviewed for build/run steps", p, 1, min(len(ctx.chunks.file_lines(ctx.repo_id, p)), 30))
                shown = True
        if not shown:
            d.line("- No setup section was found in the repository documentation.")
            suggestions.append(("Add a README section covering installation and how to run the project.", "README", None))
        d.line()
    if want("developer_guide"):
        d.line("## Developer guide (proposed)\n### Verified repository facts")
        tests = [x for _, x in g.nodes(data=True) if x.get("type") == "Test"]
        d.line(f"- {len(tests)} test function(s) were detected" + (f"; first at {_ref(tests[0]['path'], tests[0]['start_line'], tests[0]['end_line'])}" if tests else ""))
        if tests:
            ev = ctx.span(tests[0]["path"], tests[0]["start_line"], tests[0]["end_line"])
            out.claims.append(Claim(f"{len(tests)} test function(s) were detected.", "fact", [ev] if ev else []))
        tested = {v for _, v, e in g.edges(data=True) if e["type"] == "TESTS"}
        for n, x in g.nodes(data=True):
            if x.get("type") in {"Function", "Method"} and not x["name"].startswith("_") and n not in tested and x.get("language") == "python" \
                    and "tests" not in x["path"].split("/") and not x["path"].rsplit("/", 1)[-1].startswith("test_"):
                suggestions.append((f"No test is statically linked to `{x['qualified_name']}` ({x['path']}:{x['start_line']}).", x["path"], None))
        d.line()
    if suggestions:
        d.line("## Suggested improvements (recommendations, not facts)")
        for s, p, _ in suggestions[:40]:
            d.line(f"- {s}")
            out.claims.append(Claim(s, "recommendation", []))
        d.line()
    md = "\n".join(d.md)
    bundle = ctx.search(question or "project overview purpose", "documentation", k=6, kinds={"doc"}) if want("architecture") else None
    if bundle and bundle.items:
        data = ctx.llm_json("Write a short purpose-and-scope paragraph for this repository.",
                            "Use only the documentation evidence provided.", '{"summary": str, "claims": [{"text": str, "kind": "interpretation", "evidence": ["E1"]}]}',
                            question or "Describe what this project is for", bundle.items)
        if data is not None:
            out.mode = "llm+deterministic"
            out.claims += claims_from_llm(data, ctx)
            if data.get("summary"):
                md = md.replace("\n## ", f"\n## Purpose (AI-generated, verify against the cited documentation)\n{str(data['summary'])[:900]}\n\n## ", 1)
        else:
            out.notes.append("AI narrative skipped: " + (ctx.llm_error or "no local model configured"))
    out.payload.update({"markdown": md, "kind": kind})
    out.summary = f"Generated {kind} documentation ({len(md.splitlines())} lines, {sum(1 for c in out.claims if c.kind == 'fact')} cited facts)."
    return out
