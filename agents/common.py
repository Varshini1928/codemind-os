"""Shared agent plumbing: context, output type, LLM helper."""
from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Any, Callable

from agents.llm_client import LLMError, OllamaClient, evidence_block
from config.settings import Settings
from retrieval.chunk_store import ChunkStore
from retrieval.evidence_assembler import EvidenceBundle, EvidenceRegistry
from retrieval.hybrid_search import HybridSearcher
from verification.evidence_validator import Claim


@dataclass
class AgentOutput:
    summary: str = ""
    claims: list[Claim] = field(default_factory=list)
    payload: dict[str, Any] = field(default_factory=dict)
    mode: str = "deterministic"
    errors: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    insufficient: bool = False


@dataclass
class AgentContext:
    settings: Settings
    repo: dict
    registry: EvidenceRegistry
    searcher: HybridSearcher
    chunks: ChunkStore
    load_graph: Callable[[], Any]
    llm: OllamaClient | None = None
    stale: bool = False
    deadline: float = 0.0
    llm_error: str = ""
    _graph: Any = None

    @property
    def repo_id(self) -> str:
        return self.repo["id"]

    def graph(self):
        if self._graph is None:
            self._graph = self.load_graph()
        return self._graph

    def search(self, query: str, intent: str = "question", mode: str = "hybrid", k: int | None = None,
               kinds: set[str] | None = None) -> EvidenceBundle:
        b = self.searcher.search(self.repo_id, query, intent, mode, k, kinds, self.stale)
        for it in b.items:
            it.id = self.registry.add(it)
        return b

    def span(self, path: str, start: int, end: int, symbol: str = "", methods=("graph",)) -> str | None:
        return self.registry.span(path, start, end, symbol, methods)

    def llm_json(self, task: str, instructions: str, schema: str, question: str, items) -> dict | None:
        """Ask the local model; returns None (and records why) when it is unavailable or misbehaves."""
        if self.llm is None or self.llm_error:
            return None
        if self.deadline and time.time() > self.deadline:
            self.llm_error = "workflow time budget exhausted before the model was called"
            return None
        prompt = (f"Task: {task}\n{instructions}\n\nRequested JSON schema:\n{schema}\n\n"
                  f"User request: {question}\n\nRepository revision: {self.repo.get('revision')}\n\n"
                  f"{evidence_block(items)}")
        try:
            return self.llm.chat_json(prompt)
        except LLMError as e:
            self.llm_error = str(e)
            return None


def claims_from_llm(data: dict, ctx: AgentContext, key: str = "claims") -> list[Claim]:
    out = []
    for c in data.get(key, []) or []:
        if isinstance(c, dict) and isinstance(c.get("text"), str) and c["text"].strip():
            ev = c.get("evidence") or c.get("evidence_ids") or []
            ev = [e for e in ev if isinstance(e, str)] if isinstance(ev, list) else []
            out.append(Claim(c["text"].strip()[:800], str(c.get("kind", "interpretation")), ev,
                             notes=["generated by the local LLM"]))
    return out


